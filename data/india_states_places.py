def get_all_states() -> List[Dict[str, Any]]:
    """Return all 28 states data."""
    return ALL_28_STATES


def get_state_by_name(name: str) -> Optional[Dict[str, Any]]:
    """Look up a state by exact or partial name."""
    clean = name.strip().lower()
    for s in ALL_28_STATES:
        if clean in s["name"].lower() or s["name"].lower() in clean:
            return s
    return None


def get_states_by_region(region: str) -> List[Dict[str, Any]]:
    """Filter states by region (North, South, East, West, North-East, Central)."""
    if not region or region.lower() == "all":
        return ALL_28_STATES
    return [s for s in ALL_28_STATES if s["region"].lower() == region.lower()]


def get_google_maps_url(place_name: str, state_name: str) -> str:
    """Generate direct Google Maps search link."""
    from urllib.parse import quote_plus
    q = quote_plus(f"{place_name}, {state_name}, India")
    return f"https://www.google.com/maps/search/?api=1&query={q}"


